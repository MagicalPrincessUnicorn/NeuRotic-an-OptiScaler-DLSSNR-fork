"""Generate compiled defaults from the installer's canonical requirements contract."""
import json
import pathlib
import sys
root = pathlib.Path(__file__).resolve().parent.parent
contract = json.loads((root / 'tools/packaging/customer/support/NeuRotic-RenderingRequirements.json').read_text())
assert contract['schemaVersion'] == 1 and contract['architecture'] == 'x64'
d = contract['defaults']
text = '// Generated by tools/Build-RenderingRequirements.py; edit the JSON contract.\n#pragma once\nnamespace DlssNr::SetupRequirements {\n'
for name, key in [('Route','route'),('NativeResolution','nativeResolution'),('RenderingMode','renderingMode'),('Style','style'),('InputSource','inputSource'),('InputTransport','inputTransport'),('PresentInputPolicy','presentInputPolicy')]:
    text += f'inline constexpr unsigned {name} = {int(d[key])};\n'
text += 'inline constexpr bool AllowCpuFallback = ' + str(d['allowCpuFallback']).lower() + ';\n'
text += 'inline constexpr const char* SavedSelectionKeys[] = {\n'
for key in contract['savedSelectionKeys']:
    text += '    ' + json.dumps(key) + ',\n'
text += '};\n}\n'
output = root / 'OptiScaler/dlssnr/AutomaticSetupRequirements.h'
if '--check' in sys.argv:
    assert output.read_text() == text, 'Rendering requirements generated header is stale'
else:
    output.write_text(text)
