"""Losslessly package the selected RGBA logo for the native UI; no image edits."""
from pathlib import Path
from PIL import Image
import hashlib
root=Path(__file__).resolve().parents[2]
source=root/'OptiScaler/menu/brand/NeuRotic-header-v2.png'
with Image.open(source) as image:
    assert image.mode=='RGBA'
    width,height=image.size
    raw=image.tobytes()
pixels=[raw[i:i+4] for i in range(0,len(raw),4)]
visible=[(i%width,i//width) for i,pixel in enumerate(pixels) if pixel[3]>=64]
x0,y0=(min(p[0] for p in visible),min(p[1] for p in visible))
x1,y1=(max(p[0] for p in visible)+1,max(p[1] for p in visible)+1)
x0,y0=max(0,x0-2),max(0,y0-2)
x1,y1=min(width,x1+2),min(height,y1+2)
cols=sorted(set(p[0] for p in visible))
gaps=[(b-a-1,a+1,b) for a,b in zip(cols,cols[1:]) if b-a>1 and b<width*.4]
gap,left,right=max(gaps)
assert gap>5
split=(left+right)//2
packed=bytearray();i=0
def run(index):
    end=index+1
    while end<len(pixels) and end-index<32767 and pixels[end]==pixels[index]: end+=1
    return end-index
while i<len(pixels):
    count=run(i)
    if count>=3:
        packed+=(count|0x8000).to_bytes(2,'little')+pixels[i];i+=count
    else:
        start=i;i+=count
        while i<len(pixels) and i-start<32767 and run(i)<3: i+=1
        count=i-start
        packed+=count.to_bytes(2,'little')+raw[start*4:i*4]
# Verify the representation before writing generated source.
decoded=bytearray();offset=0
while offset<len(packed):
    tag=int.from_bytes(packed[offset:offset+2],'little');offset+=2
    count=tag&0x7fff
    if tag&0x8000: decoded+=packed[offset:offset+4]*count;offset+=4
    else: decoded+=packed[offset:offset+count*4];offset+=count*4
assert decoded==raw
lines=['// Generated by tools/brand/EmbedBrand.py; selected PNG pixels preserved exactly.',
       f'inline constexpr int Width={width}, Height={height};',
       f'inline constexpr int X0={x0}, Y0={y0}, X1={x1}, Y1={y1}, SplitX={split};',
       f'inline constexpr char SourceSha256[]="{hashlib.sha256(source.read_bytes()).hexdigest()}";',
       'inline constexpr unsigned char Packed[] = {']
for start in range(0,len(packed),24):
    lines.append('    '+','.join(f'0x{byte:02x}' for byte in packed[start:start+24])+',')
lines.append('};\n')
(source.parent/'BrandPixels.inc').write_text('\n'.join(lines),encoding='ascii',newline='\n')
print(f'PASS: lossless RGBA embedding {width}x{height}; {len(raw)} raw bytes -> {len(packed)} packed bytes; content {x0},{y0}..{x1},{y1}; mark/wordmark split {split}')
