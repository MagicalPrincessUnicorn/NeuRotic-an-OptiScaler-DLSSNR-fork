"""Emit V6 tables from preserved included packs; never rewrite source translations.

Machine-draft originals remain provenance/import material. Native ValidatePack
is authoritative; these build-input checks preserve stale review revisions.
"""
from pathlib import Path
import json
import re
import inventory
ROOT=Path(__file__).resolve().parents[2]
LOCALES=['zh-CN','ru','es','pt-BR','de','ja','fr','pl','ko']
NAMES=['简体中文','Русский','Español','Português (Brasil)','Deutsch','日本語','Français','Polski','한국어']
FORMAT=re.compile(r'%(?:[-+#0]*(?:\d+|\*)?(?:\.(?:\d+|\*))?(?:hh|ll|[hljztL]|I64)?[diuoxXfFeEgGaAcspn]|%)|\{[A-Za-z_][A-Za-z0-9_]*\}')
def validate_translation(text,entry):
    if not isinstance(text,str) or not text.strip() or len(text.encode('utf-8'))>32768 or any(ord(c)<32 and c not in '\n\r\t' or ord(c)==127 for c in text):
        raise ValueError('Invalid translation text: '+entry['id'])
    if not entry['line_breaks'] and ('\n' in text or '\r' in text):raise ValueError('Unexpected line break: '+entry['id'])
    if any(term not in text for term in entry['preserve']):raise ValueError('Missing preserved term: '+entry['id'])
    source,target=FORMAT.findall(entry['english']),FORMAT.findall(text)
    named=lambda tokens:sorted(t for t in tokens if t.startswith('{'))
    printf=lambda tokens:[t for t in tokens if not t.startswith('{')]
    if named(source)!=named(target) or printf(source)!=printf(target):raise ValueError('Translation format mismatch: '+entry['id'])
    before,after=FORMAT.sub('',entry['english']),FORMAT.sub('',text)
    if any(before.count(c)!=after.count(c) for c in '%{}'):raise ValueError('Unknown format directive: '+entry['id'])
def load_pack(locale,english):
    pack=json.loads((ROOT/f'localization/bundled/{locale}.nrlang').read_text(encoding='utf-8'))
    allowed={'formatVersion','packId','locale','language','name','author','version','desktop','in_game'}
    if set(pack)!=allowed or pack['formatVersion']!=1 or pack['locale']!=locale or pack['packId']!='included-'+locale:
        raise ValueError('Invalid included pack identity/fields: '+locale)
    for key in ('language','name','author','version'):
        value=pack[key]
        if not isinstance(value,str) or not value or len(value.encode('utf-8'))>255 or any(c in value for c in '\n\r\t\0'):raise ValueError('Invalid pack metadata: '+locale+'/'+key)
    ids=set()
    for surface in ('desktop','in_game'):
        if not isinstance(pack[surface],list):raise ValueError('Invalid surface array: '+locale)
        for row in pack[surface]:
            id=row['id']
            if id in ids or id not in english or english[id]['surface']!=surface:raise ValueError('Invalid included ID/surface: '+locale+'/'+id)
            ids.add(id)
            if set(row)-{'id','translation','revision','note'}:raise ValueError('Unexpected included row field: '+id)
            if type(row.get('revision')) is not int or not 0<=row['revision']<=0xffffffff:raise ValueError('Invalid translation revision: '+id)
            validate_translation(row['translation'],english[id])
    return pack
def embedded_packs(packs):
    lines=['// Generated by tools/localization/bundles.py; preserved included data.']
    for index,pack in enumerate(packs):
        data=json.dumps(pack,ensure_ascii=True,separators=(',',':'))
        lines.append(f'static const char* const EmbeddedPack{index}Chunks[] = {{')
        lines+=['R"NR_BUNDLE('+data[i:i+12000]+')NR_BUNDLE",' for i in range(0,len(data),12000)]
        lines.append('};')
    lines.append('static const EmbeddedPack EmbeddedPacks[] = {')
    for index,pack in enumerate(packs):
        lines.append(' {'+json.dumps(pack['packId'])+','+json.dumps(pack['locale'])+f',EmbeddedPack{index}Chunks,std::size(EmbeddedPack{index}Chunks)'+'},')
    return '\n'.join(lines+['};',''])
def build():
    entries=json.loads((ROOT/'localization/english.json').read_text(encoding='utf-8'));inventory.validate(entries)
    english={e['id']:e for e in entries}
    # Validate all sources before replacing either selected consumer's generated data.
    packs=[load_pack(locale,english) for locale in LOCALES]
    outputs={}
    for consumer,relative in inventory.CONSUMER_OUTPUTS.items():
        known={e['id'] for e in inventory.consumer_entries(entries,consumer)}
        # Release native order was lexical; desktop order follows its picker.
        ordered=sorted(packs,key=lambda pack:pack['locale']) if consumer=='runtime' else packs
        selected=[dict(pack,**{surface:[row for row in pack[surface] if row['id'] in known] for surface in ('desktop','in_game')}) for pack in ordered]
        outputs[ROOT/relative/'BundledPacks.inc']=embedded_packs(selected)
    for path,text in outputs.items():path.write_text(text,encoding='utf-8',newline='\n')
    print('PASS preserved source packs emitted for runtime and desktop; native validation/fit pending')
if __name__=='__main__':build()
